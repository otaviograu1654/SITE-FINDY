CREATE TABLE IF NOT EXISTS portfolio_prestadores (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prestador_id BIGINT NOT NULL REFERENCES prestadores(id),
    legenda VARCHAR(160) NOT NULL DEFAULT '',
    conteudo BYTEA NOT NULL CHECK (octet_length(conteudo) BETWEEN 1 AND 2097152),
    tipo VARCHAR(10) NOT NULL CHECK (tipo IN ('image/jpeg','image/png')),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_portfolio_prestador ON portfolio_prestadores(prestador_id);
