-- Cria a tabela de notas e comentários associados às solicitações de serviço.

CREATE TABLE avaliacoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    solicitacao_id BIGINT NOT NULL,
    avaliador_id BIGINT NOT NULL,
    avaliado_id BIGINT NOT NULL,

    nota INTEGER NOT NULL,
    comentario TEXT,

    data_avaliacao TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_avaliacoes_solicitacao
        FOREIGN KEY (solicitacao_id)
        REFERENCES solicitacoes (id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_avaliacoes_avaliador
        FOREIGN KEY (avaliador_id)
        REFERENCES usuarios (id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_avaliacoes_avaliado
        FOREIGN KEY (avaliado_id)
        REFERENCES usuarios (id)
        ON DELETE RESTRICT,

    CONSTRAINT uq_avaliacoes_solicitacao
        UNIQUE (solicitacao_id),

    CONSTRAINT ck_avaliacoes_nota
        CHECK (nota BETWEEN 1 AND 5),

    CONSTRAINT ck_avaliacoes_pessoas
        CHECK (avaliador_id <> avaliado_id)
);

CREATE INDEX idx_avaliacoes_avaliador
    ON avaliacoes (avaliador_id);

CREATE INDEX idx_avaliacoes_avaliado
    ON avaliacoes (avaliado_id);