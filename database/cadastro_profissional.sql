BEGIN;
ALTER TABLE usuarios ADD COLUMN IF NOT EXISTS bairro VARCHAR(100);
ALTER TABLE prestadores ADD COLUMN IF NOT EXISTS iniciante BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE prestadores DROP CONSTRAINT IF EXISTS ck_prestadores_status;
ALTER TABLE prestadores ADD CONSTRAINT ck_prestadores_status CHECK
 (status_aprovacao IN ('PENDENTE','APROVADO','RECUSADO','CORRECAO_SOLICITADA','RECUSADO_DEFINITIVO'));
CREATE TABLE IF NOT EXISTS prestador_habilidades (
 prestador_id BIGINT NOT NULL REFERENCES prestadores(id) ON DELETE CASCADE,
 habilidade VARCHAR(180) NOT NULL, PRIMARY KEY(prestador_id, habilidade)
);
CREATE TABLE IF NOT EXISTS analises_prestadores (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 prestador_id BIGINT NOT NULL REFERENCES prestadores(id) ON DELETE RESTRICT,
 administrador_id BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
 decisao VARCHAR(30) NOT NULL CHECK (decisao IN ('APROVADO','CORRECAO_SOLICITADA','RECUSADO_DEFINITIVO','RECUSADO')),
 motivo TEXT, data_analise TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CHECK (decisao='APROVADO' OR (motivo IS NOT NULL AND LENGTH(TRIM(motivo))>0))
);
CREATE INDEX IF NOT EXISTS idx_analises_prestador ON analises_prestadores(prestador_id);
-- Preserva a última decisão antiga disponível, sem inventar decisões anteriores.
INSERT INTO analises_prestadores(prestador_id,administrador_id,decisao,motivo,data_analise)
 SELECT p.id,p.analisado_por,p.status_aprovacao,p.motivo_recusa,p.data_analise
 FROM prestadores p WHERE p.analisado_por IS NOT NULL AND p.data_analise IS NOT NULL
 AND p.status_aprovacao IN ('APROVADO','RECUSADO')
 AND NOT EXISTS (SELECT 1 FROM analises_prestadores a WHERE a.prestador_id=p.id);
COMMIT;
