-- Cria as tabelas de contas e perfis profissionais, com suas permissões e regras de aprovação.

-- Conta unica para contratar e oferecer serviços
CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    nome VARCHAR(100) NOT NULL,
    email VARCHAR(100) NOT NULL,
    senha_hash VARCHAR(255) NOT NULL,
    
    papel VARCHAR(20) NOT NULL DEFAULT 'USUARIO',
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    data_cadastro TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    telefone VARCHAR(20),
    cidade VARCHAR(100),
    estado VARCHAR(2),
    foto VARCHAR(500),

    CONSTRAINT ck_usuarios_papel
        CHECK (papel IN ('USUARIO', 'ADMIN'))
);

-- Evita contas com o mesmo e-mail
CREATE UNIQUE INDEX uq_usuarios_email
    ON usuarios (LOWER(TRIM(email)));

-- Perfil profissional opcional, ligado à conta existente.
CREATE TABLE prestadores (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    usuario_id BIGINT NOT NULL,

    descricao_profissional TEXT,
    experiencia TEXT,
    regiao_atendimento VARCHAR(255),

    status_aprovacao VARCHAR(20) NOT NULL DEFAULT 'PENDENTE',
    motivo_recusa TEXT,
    analisado_por BIGINT,
    data_analise TIMESTAMPTZ,

    ativo BOOLEAN NOT NULL DEFAULT TRUE,

    data_cadastro TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_prestadores_usuario
        UNIQUE (usuario_id),

    CONSTRAINT fk_prestadores_usuario
        FOREIGN KEY (usuario_id)
        REFERENCES usuarios (id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_prestadores_administrador
        FOREIGN KEY (analisado_por)
        REFERENCES usuarios (id)
        ON DELETE RESTRICT,

    CONSTRAINT ck_prestadores_status
        CHECK (
            status_aprovacao IN (
                'PENDENTE',
                'APROVADO',
                'RECUSADO'
            )
        ),

    CONSTRAINT ck_prestadores_motivo_recusa
        CHECK (
            status_aprovacao <> 'RECUSADO'
            OR (
                motivo_recusa IS NOT NULL
                AND LENGTH(TRIM(motivo_recusa)) > 0
            )
        )
);