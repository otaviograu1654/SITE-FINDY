-- Cria a tabela dos serviços oferecidos, vinculando prestador, categoria, preço e forma de cobrança.

CREATE TABLE servicos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    prestador_id BIGINT NOT NULL,
    categoria_id BIGINT NOT NULL,

    titulo VARCHAR(120) NOT NULL,
    descricao TEXT,

    preco NUMERIC(10, 2),
    unidade_cobranca VARCHAR(10) NOT NULL DEFAULT 'SERVICO',

    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    data_cadastro TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_servicos_prestador
        FOREIGN KEY (prestador_id)
        REFERENCES prestadores (id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_servicos_categoria
        FOREIGN KEY (categoria_id)
        REFERENCES categorias (id)
        ON DELETE RESTRICT,

    CONSTRAINT ck_servicos_preco
        CHECK (preco >= 0),

    CONSTRAINT ck_servicos_unidade
        CHECK (
            unidade_cobranca IN ('HORA', 'DIARIA', 'SERVICO')
        )
);

CREATE INDEX idx_servicos_prestador
    ON servicos (prestador_id);

CREATE INDEX idx_servicos_categoria
    ON servicos (categoria_id);