CREATE TABLE solicitacoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    cliente_id BIGINT NOT NULL,
    servico_id BIGINT NOT NULL,

    mensagem TEXT,
    status VARCHAR(30) NOT NULL DEFAULT 'PENDENTE',

    data_inicio TIMESTAMPTZ,
    duracao_horas NUMERIC(6, 2),

    endereco VARCHAR(255),
    bairro VARCHAR(100),
    cidade VARCHAR(100),
    estado VARCHAR(2),

    -- Valores combinados para esta contratação.
    valor_unitario NUMERIC(10, 2),
    unidade_cobranca VARCHAR(10),
    subtotal NUMERIC(10, 2),
    taxa NUMERIC(10, 2) NOT NULL DEFAULT 0,
    total NUMERIC(10, 2),

    forma_pagamento VARCHAR(20),

    data_solicitacao TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    data_conclusao TIMESTAMPTZ,

    CONSTRAINT fk_solicitacoes_cliente
        FOREIGN KEY (cliente_id)
        REFERENCES usuarios (id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_solicitacoes_servico
        FOREIGN KEY (servico_id)
        REFERENCES servicos (id)
        ON DELETE RESTRICT,

    CONSTRAINT ck_solicitacoes_status
        CHECK (
            status IN (
                'PENDENTE',
                'ACEITA',
                'RECUSADA',
                'EM_ANDAMENTO',
                'AGUARDANDO_CONFIRMACAO',
                'CONCLUIDA',
                'CANCELADA'
            )
        ),

    CONSTRAINT ck_solicitacoes_duracao
        CHECK (duracao_horas > 0),

    CONSTRAINT ck_solicitacoes_valor_unitario
        CHECK (valor_unitario >= 0),

    CONSTRAINT ck_solicitacoes_subtotal
        CHECK (subtotal >= 0),

    CONSTRAINT ck_solicitacoes_taxa
        CHECK (taxa >= 0),

    CONSTRAINT ck_solicitacoes_total
        CHECK (total >= 0),

    CONSTRAINT ck_solicitacoes_soma
        CHECK (
            total IS NULL
            OR (
                subtotal IS NOT NULL
                AND total = subtotal + taxa
            )
        ),

    CONSTRAINT ck_solicitacoes_unidade
        CHECK (
            unidade_cobranca IN ('HORA', 'DIARIA', 'SERVICO')
        ),

    CONSTRAINT ck_solicitacoes_pagamento
        CHECK (
            forma_pagamento IN ('PIX', 'CARTAO', 'DINHEIRO')
        ),

    CONSTRAINT ck_solicitacoes_data_conclusao
        CHECK (
            status <> 'CONCLUIDA'
            OR data_conclusao IS NOT NULL
        )
);

CREATE INDEX idx_solicitacoes_cliente
    ON solicitacoes (cliente_id);

CREATE INDEX idx_solicitacoes_servico
    ON solicitacoes (servico_id);

CREATE INDEX idx_solicitacoes_status
    ON solicitacoes (status);