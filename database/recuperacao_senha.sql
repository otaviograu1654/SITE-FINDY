-- Cria a tabela dos hashes dos links de recuperação, com prazo de validade e registro de uso.

CREATE TABLE recuperacoes_senha (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    usuario_id BIGINT NOT NULL,

    token_hash VARCHAR(64) NOT NULL UNIQUE,

    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expira_em TIMESTAMPTZ NOT NULL,
    usado_em TIMESTAMPTZ,

    CONSTRAINT fk_recuperacoes_usuario
        FOREIGN KEY (usuario_id)
        REFERENCES usuarios (id)
        ON DELETE CASCADE,

    CONSTRAINT ck_recuperacoes_expiracao
        CHECK (expira_em > criado_em)
);

CREATE INDEX idx_recuperacoes_usuario
    ON recuperacoes_senha (usuario_id);